import { expect, test } from 'vitest';
import { newPasswordProblem, PASSWORD_RULES_ATTRIBUTE, unmetPasswordRules } from './passwordRules.ts';

const ids = (password: string) => unmetPasswordRules(password).map((rule) => rule.id);

test('a password meets each rule on its own', () => {
  expect(ids('')).toStrictEqual(['length', 'lower', 'upper', 'digit', 'symbol']);
  expect(ids('abcdefghij')).toStrictEqual(['upper', 'digit', 'symbol']);
  expect(ids('Abcdefghi1')).toStrictEqual(['symbol']);
  expect(ids('Abcdefgh1!')).toStrictEqual([]);
});

test('letters and digits from any script count, and any other character but a space is a symbol', () => {
  expect(ids('Ébène-àvec1')).toStrictEqual([]);
  for (const symbol of [...'!?@#$%^&*()-_=+[]{};:\'",.<>/\\|`~€£§°']) {
    expect(ids(`Abcdefgh1${symbol}`), symbol).toStrictEqual([]);
  }
});

test('a space is allowed and counts toward the length, but is no symbol', () => {
  expect(ids('Abcdefgh 12')).toStrictEqual(['symbol']);
  expect(ids('Correct horse battery 9!')).toStrictEqual([]);
  expect(ids(' Leading and trailing 7! '), 'spaces are kept as typed').toStrictEqual([]);
});

test('length counts characters, not UTF-16 units', () => {
  expect(ids('Aa1!🙂🙂🙂🙂🙂'), 'nine characters, fourteen units').toStrictEqual(['length']);
});

test('passwords generated by password managers pass', () => {
  expect(newPasswordProblem('kugfaw-7Tydxa-qepvob'), 'Apple style').toBe(null);
  expect(newPasswordProblem('X9!mQ2#vLp8@wZr4^tB6'), '1Password style').toBe(null);
});

test('the server refuses a new password that breaks a rule, and caps its length', () => {
  expect(newPasswordProblem('short')).toStrictEqual({ code: 'passwordRules' });
  expect(newPasswordProblem(`Aa1!${'x'.repeat(130)}`)).toStrictEqual({ code: 'passwordTooLong', params: { max: 128 } });
});

test('the passwordrules attribute needs a symbol other than a space, and allows spaces', () => {
  expect(PASSWORD_RULES_ATTRIBUTE).toBe(
    'minlength: 10; maxlength: 128; required: lower; required: upper; required: digit; required: [-~!@#$%^&*_+=`|(){}[:;"\'<>,.?]]; allowed: lower, upper, digit, special;'
  );
});
